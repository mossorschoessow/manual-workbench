/* ---------- 運行時 ---------- */
let LANG = 'en';
let plural = new Intl.PluralRules('en');

function detectLang() {
  try {
    const saved = localStorage.getItem('lang');
    if (saved && DICT[saved]) return saved;
  } catch { /* 隱私模式等 */ }
  for (const raw of navigator.languages || [navigator.language || 'en']) {
    const l = raw.toLowerCase();
    if (l.startsWith('zh')) {
      return /hant|tw|hk|mo/.test(l) ? 'zh-Hant' : 'zh-Hans';
    }
    const base = l.split('-')[0];
    if (DICT[base]) return base;
  }
  return 'en';
}

function setLang(lang, save) {
  LANG = DICT[lang] ? lang : 'en';
  plural = new Intl.PluralRules(LANG);
  if (save) { try { localStorage.setItem('lang', LANG); } catch { /* ignore */ } }
  document.documentElement.lang = LANG;
}

/** 取翻譯：t('key', { n: 3 }) */
function t(key, params) {
  let v = DICT[LANG][key];
  if (v === undefined) v = DICT.en[key];
  if (v === undefined) return key;
  if (typeof v === 'object') {
    const n = params && typeof params.n === 'number' ? params.n : 0;
    v = v[plural.select(n)] ?? v.other;
  }
  if (params) v = v.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
  return v;
}

/** 把頁面上帶 data-i18n* 屬性的元素換成當前語言 */
function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  document.title = t('app.title');
}

